JP = re.compile(r"[\u3040-\u30ff\u4e00-\u9fff\uff01-\uff5e\u3001\u3002\u300c\u300d]")


def papers():
    src = (AM / "papers_longtable.tex").read_text(encoding="utf-8").split("\n")
    rows = []
    for l in src:
        if not re.match(r"^\d+ & ", l):
            continue
        cols = re.split(r"(?<!\\) & ", l.rstrip().rstrip("\\").rstrip())
        assert len(cols) == 8, l[:80]
        no, title, year, typ, field, doi, route, neq = cols
        head, sep, tail = title.partition("\\newline")
        head = TITLE.get(no, head).replace("†", "\\textsuperscript{\\dag}")
        title = head + sep + tail
        fld = FIELD[field].replace("Thermodynamics", "Thermodyn.").replace("Electrochemistry", "Electrochem.")
        cols = [no, title, year, TYPE[typ], fld, doi, route, neq]
        line = " & ".join(cols) + " \\\\"
        assert not JP.search(line), line[:120]
        rows.append(line)
    assert len(rows) == 329
    hdr = r"""% 2026-10-21 generated by make_appendix_tables.py from docs/appendix_materials/papers_longtable.tex (English labels).
% Types follow the OpenAlex classification as of 2026-10-20 (it may differ from the classification at collection time).
\begin{footnotesize}
\setlength{\tabcolsep}{2.5pt}
\begin{longtable}{@{}r>{\raggedright\arraybackslash}p{0.31\linewidth}c>{\raggedright\arraybackslash}p{0.09\linewidth}>{\raggedright\arraybackslash}p{0.135\linewidth}>{\raggedright\arraybackslash}p{0.155\linewidth}cr@{}}
\caption{The 329 documents among the sources of the equation database. Route: M = collected by hand early in this work (24), S = retrieved by the Semantic Scholar search early in this work (15), O = the OpenAlex search by field (118), F1--F3 = the supplementary OpenAlex searches 1--3 (88, 33, and 48), P = the additional search for optics (3). A dagger (\dag) marks a title inferred from the file name and the equations in the database, because the PDF is not at hand. ``Eqs.'' gives the number of equations in the database. A document entered as several sources occupies one row per source.}\label{tab:papers}\\
\toprule
No. & Title (below: source identifier in the database) & Year & Type & Field & DOI / OpenAlex ID & Route & Eqs. \\
\midrule
\endfirsthead
\toprule
No. & Title (below: source identifier in the database) & Year & Type & Field & DOI / OpenAlex ID & Route & Eqs. \\
\midrule
\endhead
\midrule
\multicolumn{8}{r}{(continued on the next page)}\\
\endfoot
\bottomrule
\endlastfoot
"""
    (OUT / "appendix_papers.tex").write_text(hdr + "\n".join(rows) + "\n\\end{longtable}\n\\end{footnotesize}\n",
                                             encoding="utf-8")


def search_terms():
    rows = list(csv.DictReader(open(AM / "search_terms.csv", encoding="utf-8-sig")))
    assert len(rows) == 32
    keys = ["取得できた PDF（32domains）", "補強1で取得", "補強2で取得", "補強3で取得", "光学のみで取得",
            "フォルダの PDF 数（2026-10-20）", "式が DB に入った PDF 数"]
    tot = [0] * len(keys)
    out = []
    for r in rows:
        vals = []
        for i, k in enumerate(keys):
            v = r[k].strip()
            if v and v != "0" or (k == keys[0] and v == "0"):
                tot[i] += int(v)
                vals.append(v)
            else:
                vals.append("---")
        out.append(f"{FIELD[r['分野']]} & {r['検索語（fetch_papers_32domains.py）']} & " + " & ".join(vals) + " \\\\")
    assert tot == [124, 92, 36, 51, 3, 306, 290], tot
    hdr = r"""% 2026-10-21 generated by make_appendix_tables.py from docs/appendix_materials/search_terms.csv (English labels).
\begin{footnotesize}
\setlength{\tabcolsep}{3pt}
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.17\linewidth}>{\raggedright\arraybackslash}p{0.40\linewidth}rrrrrrr@{}}
\caption{Search term of each field and the numbers of PDFs obtained. We sent each search term to OpenAlex followed by ``mathematical model differential equation.'' O counts the PDFs obtained by this search; F1--F3 count those obtained by the supplementary searches, which used three to five other search terms per field; P counts those obtained by the additional search for optics. The supplementary searches stopped when the field held 10 PDFs. ``DB'' counts the PDFs whose equations entered the database.}\label{tab:search}\\
\toprule
Field & Search term & O & F1 & F2 & F3 & P & Total & DB \\
\midrule
\endfirsthead
\toprule
Field & Search term & O & F1 & F2 & F3 & P & Total & DB \\
\midrule
\endhead
\bottomrule
\endlastfoot
"""
    tail = "\\midrule\nTotal & & " + " & ".join(str(t) for t in tot) + " \\\\\n\\end{longtable}\n\\end{footnotesize}\n"
    (OUT / "appendix_search_terms.tex").write_text(hdr + "\n".join(out) + "\n" + tail, encoding="utf-8")


