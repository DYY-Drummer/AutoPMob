def place_note(page, anchor_rect, title, body):
    page_rect = page.rect
    point_x = page_rect.width - 30
    point_y = max(30, min(anchor_rect.y0, page_rect.height - 30))
    pt = fitz.Point(point_x, point_y)
    annot = page.add_text_annot(pt, body, icon="Comment")
    annot.set_info(title=title, content=body)
    annot.set_colors(stroke=(1.0, 0.6, 0.0))
    annot.update()


def main():
    doc = fitz.open(SRC)
    print(f"PDF: {len(doc)} pages")

    placed = 0
    missed = []

    for i, (anchor, kp, kato, fix) in enumerate(ANNOTATIONS, 1):
        found = False
        for pno, page in enumerate(doc):
            rects = page.search_for(anchor)
            if rects:
                # 最初のヒットに対してハイライト + 付箋
                r = rects[0]
                # ハイライトは全一致箇所
                for rr in rects:
                    annot = page.add_highlight_annot(rr)
                    annot.set_colors(stroke=COLOR_HL)
                    annot.update()
                title = f"#{i:02d} [加藤先生指摘 SK p.{kp}]"
                body = (
                    f"#{i:02d} [加藤先生指摘 SK.pdf p.{kp}]\n\n"
                    f"■ 指摘：{kato}\n\n"
                    f"■ 対応：{fix}"
                )
                place_note(page, r, title, body)
                placed += 1
                found = True
                print(f"  #{i:02d} p{pno+1} OK : {anchor[:30]}")
                break
        if not found:
            missed.append((i, anchor, kato))
            print(f"  #{i:02d} NOT FOUND: {anchor!r}")

    doc.save(OUT)
    doc.close()
    print(f"\n配置済: {placed}/{len(ANNOTATIONS)}")
    if missed:
        print("\n未配置:")
        for i, a, k in missed:
            print(f"  #{i:02d}: {a!r}")
    print(f"\n出力: {OUT}")


if __name__ == "__main__":
    main()
