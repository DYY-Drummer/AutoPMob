def reason(key: str, short: bool = False) -> str:
    if key in EDITS:
        return EDITS[key]
    if key not in KATO:
        return key  # 自由記述の理由
    page, phrase, comment = KATO[key]
    if short and "。" in comment[:-1]:
        comment = comment[: comment.index("。") + 1] + "…"
    # 引用の中のかぎ括弧は二重かぎ括弧にする
    inner = str.maketrans("「」", "『』")
    comment = comment.translate(inner)
    phrase = phrase.translate(inner) if phrase else None
    if phrase is None:
        return f"8/31 版 p.{page} の付箋「{comment}」"
    return f"8/31 版 p.{page}「{phrase}」へのコメント「{comment}」"


@dataclass
class Note:
    start: str
    end: str | None
    cat: str            # y / b / o
    fix: str
    reasons: list[str] = field(default_factory=list)  # KATO / EDITS のキー、または自由記述
    short: set[str] = field(default_factory=set)      # コメントを 1 文目だけ引くキー
    pre: str = ""       # start の直前の文字列（start だけで一意に決まらないとき。ハイライトしない）
    skip: tuple[str, str] | None = None  # 範囲の途中に入る表や図（この最初と最後の文字列の間はハイライトしない）
    head: str | None = None  # コメントの見出し（既定は色ごとに 修正／追加／一部対応）

    def content(self) -> str:
        head = self.head or {"y": "修正", "b": "追加", "o": "一部対応"}[self.cat]
        rs = [reason(k, k in self.short) for k in self.reasons]
        if len(rs) == 1:
            return f"{head}：{self.fix}\n理由：{rs[0]}"
        return f"{head}：{self.fix}\n理由：\n" + "\n".join("・" + r for r in rs)


