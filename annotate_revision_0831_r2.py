@dataclass
class Note:
    start: str
    end: str | None
    cat: str            # y / b / r / o
    fix: str
    reasons: list[str] = field(default_factory=list)
    pre: str = ""
    skip: tuple[str, str] | None = None

    def content(self) -> str:
        rs = [reason(k) for k in self.reasons]
        if len(rs) == 1:
            return f"{HEADS[self.cat]}：{self.fix}\n理由：{rs[0]}"
        return f"{HEADS[self.cat]}：{self.fix}\n理由：\n" + "\n".join("・" + r for r in rs)


