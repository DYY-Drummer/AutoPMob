def label(ids: str) -> str:
    return "・".join(r"\#" + s for s in ids.split())


def apply(text: str, m: Mark) -> str:
    key = m.pre + m.start
    n = text.count(key)
    if n != 1:
        sys.exit(f"開始の文字列が {n} か所にある: {key[:60]!r}")
    i = text.index(key) + len(m.pre)
    if m.end is None:
        j = i + len(m.start)
    else:
        j = text.find(m.end, i + len(m.start))
        if j < 0:
            sys.exit(f"終わりの文字列がない: {m.end[:60]!r}（開始 {m.start[:40]!r}）")
        j += len(m.end)
    span = text[i:j]
    if "\n\n" in span or "\\begin{" in span or "\\item" in span:
        sys.exit(f"ハイライトが段落や環境をまたぐ: {m.start[:40]!r}")
    if span.count("{") != span.count("}"):
        sys.exit(f"ハイライトの括弧が対応しない: {m.start[:40]!r}")
    body = rf"\hlmark{{{m.cat}}}{{{span}}}"
    if m.ids:
        pre = m.prefix or PREFIX[m.cat]
        fix, why = (re.sub(r"(?<!\\)#", r"\\#", t) for t in (m.fix, m.why))
        body = rf"\rnote{{{m.cat}}}{{{label(m.ids)}}}{{{pre}}}{{{fix}}}{{{why}}}" + body
    return text[:i] + body + text[j:]


