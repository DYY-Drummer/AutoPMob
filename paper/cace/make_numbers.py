# ---- formatting ------------------------------------------------------------------------------

def _number(x):
    """A finite number, or stop: a JSON null or NaN must never reach the text as "None" or "nan"."""
    if isinstance(x, bool) or not isinstance(x, (int, float)) or not math.isfinite(x):
        raise ValueError(f"not a finite number: {x!r}")
    return x


def fmt(x: float, nd: int = 3) -> str:
    """Fixed decimals; a value that rounds to zero prints without a minus sign."""
    s = f"{_number(x):.{nd}f}"
    return f"{0:.{nd}f}" if float(s) == 0 else s


def diff(a: float, b: float, nd: int = 3, signed: bool = True) -> str:
    """a - b from the raw values, rounded. signed adds + or -; a difference that rounds to zero has no sign."""
    d = a - b
    s = fmt(abs(d), nd)
    if float(s) == 0 or not signed:
        return s
    return ("+" if d > 0 else "-") + s


def pct(x: float, nd: int = 1) -> str:
    """A fraction as a percentage number (without the % sign)."""
    return fmt(100 * _number(x), nd)


def count(n: int) -> str:
    return f"{int(_number(n)):,}".replace(",", "{,}")


def money(x: float) -> str:
    return f"{_number(x):,.2f}".replace(",", "{,}")


# ---- registry and lookup ----------------------------------------------------------------------

class Registry:
    """Macro name -> value. Names are letters only and unique."""

    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def add(self, name: str, value: str) -> None:
        if not re.fullmatch(r"[A-Za-z]+", name or ""):
            raise ValueError(f"macro name must be letters only: {name!r}")
        if name in self.values:
            raise ValueError(f"duplicate macro name: {name}")
        value = str(value)
        if not value.strip() or re.search(r"(?<![A-Za-z])(None|nan|NaN|inf)(?![A-Za-z])", value):
            raise ValueError(f"\\{name} has no usable value: {value!r}")
        self.values[name] = value

    def render(self) -> str:
        head = ["% Generated by make_numbers.py from the result JSON files. Do not edit by hand.",
                "% Regenerate: python3 paper/cace/make_numbers.py"]
        return "\n".join(head + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.values.items())]) + "\n"


def get(obj, path, source: str):
    """Look up a dotted path (or a sequence of keys, for keys that contain dots). Names the file and path on failure."""
    keys = path.split(".") if isinstance(path, str) else list(path)
    cur = obj
    for k in keys:
        try:
            cur = cur[k]
        except (KeyError, IndexError, TypeError):
            raise KeyError(f"{source}: missing key path {'.'.join(map(str, keys))!r} (at {k!r})") from None
    return cur


class _Dict(dict):
    """A JSON object that names its file and key path when a key is missing."""

    def __init__(self, data: dict, source: str, path: str) -> None:
        super().__init__((k, _track(v, source, f"{path}.{k}" if path else str(k))) for k, v in data.items())
        self._source, self._path = source, path

    def __missing__(self, key):
        raise KeyError(f"{self._source}: missing key {self._path + '.' if self._path else ''}{key}")


class _List(list):
    """A JSON array that names its file and key path when an index is out of range."""

    def __init__(self, data: list, source: str, path: str) -> None:
        super().__init__(_track(v, source, f"{path}[{i}]") for i, v in enumerate(data))
        self._source, self._path = source, path

    def __getitem__(self, i):
        try:
            return super().__getitem__(i)
        except IndexError:
            raise IndexError(f"{self._source}: missing index {self._path}[{i}]") from None


def _track(value, source: str, path: str):
    if isinstance(value, dict):
        return _Dict(value, source, path)
    if isinstance(value, list):
        return _List(value, source, path)
    return value


@lru_cache(maxsize=None)
def load(path: Path):
    """A JSON file whose objects and arrays stop with the file name and the key path when a lookup fails."""
    return _track(json.loads(Path(path).read_text(encoding="utf-8")), Path(path).name, "")


# ---- macro groups -----------------------------------------------------------------------------

def code_constant(path, pattern: str) -> str:
    """The value that `pattern` (one group) captures in a source file. Stops when it is missing or ambiguous."""
    found = set(re.findall(pattern, Path(path).read_text(encoding="utf-8")))
    if len(found) != 1:
        raise ValueError(f"{Path(path).name}: expected one value for {pattern!r}, found {sorted(found)}")
    return found.pop()


def sdiff(delta: float, nd: int = 3) -> str:
    """A signed difference that is already a raw difference (for math mode)."""
    return diff(delta, 0.0, nd)


def require(cond: bool, claim: str) -> None:
    """Stop when the data no longer support a sentence that the text states without a number."""
    if not cond:
        raise ValueError(f"the text claims: {claim} -- the data no longer support it")


def _db_counts() -> dict:
    """The counts of db_counts.json; stops when the database or the cases changed after they were taken."""
    name = DB_COUNTS.name
    db = load(DB_COUNTS)
    for path, key in ((DB_FILE, "unified_equations_sha256"), (CASES_FILE, "training_cases_sha256")):
        if Path(path).exists() and hashlib.sha256(Path(path).read_bytes()).hexdigest() != get(db, key, name):
            raise ValueError(f"{name} is stale: {Path(path).name} changed -- run python3 paper/cace/db_counts.py")
    return db


