"""Generate numbers.tex: every number of the paper as a TeX macro, read from the result JSON files.

The text and tables of the paper use only these macros, so they cannot drift from the data.
Run after any result JSON changes:
    python3 paper/cace/make_numbers.py            # writes paper/cace/numbers.tex
    python3 paper/cace/make_numbers.py --check    # exit 1 if numbers.tex differs from a fresh build

Conventions
  - Metrics print with three decimals; a value that rounds to zero prints without a minus sign.
  - A difference is rounded after subtracting the raw values (never the rounded ones).
  - Macro names are letters only (TeX reads \\Rec20A as \\Rec followed by "20A").
    Metric: Rec (Recall@20), Map (MAP), MapTw (MAP@20), RPrec (R-Precision).
    Setting: A (all 1,731 cases), B (the 1,000 synthesized cases).
    Method: Base (classical baseline), Bm (BM25 variant), EFive (E5 variant), Prop (static reranking),
            Infer (greedy at inference), Greedy (learned greedy), Opus, Haiku.  Suffix SD = standard deviation over 10 splits.
  - Signed differences (+0.075, -0.002) are meant for math mode: $\\DiffRecAPropBase$.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "numbers.tex"
KATO = ROOT / "experiments" / "kato1021"
LLM = ROOT / "experiments" / "llm_db_baseline"

METRICS = {"Recall@20": "Rec", "MAP": "Map", "MAP@20": "MapTw", "R-Precision": "RPrec"}
METHODS = {"baseline_tfidf": "Base", "baseline_bm25": "Bm", "baseline_e5": "EFive",
           "proposed_static": "Prop", "proposed_infer": "Infer", "proposed_train": "Greedy"}
LLMS = {"Opus 5.5": "Opus", "Haiku 5.5": "Haiku"}
KINDS = {"single": "Single", "cross": "Cross", "synth": "Synth"}


# ---- formatting ------------------------------------------------------------------------------

def fmt(x: float, nd: int = 3) -> str:
    """Fixed decimals; a value that rounds to zero prints without a minus sign."""
    s = f"{x:.{nd}f}"
    return f"{0:.{nd}f}" if float(s) == 0 else s


def diff(a: float, b: float, nd: int = 3, signed: bool = True) -> str:
    """a - b from the raw values, rounded. signed adds + or -; a difference that rounds to zero has no sign."""
    d = a - b
    s = fmt(abs(d), nd)
    if float(s) == 0 or not signed:
        return s
    return ("+" if d > 0 else "-") + s


def pct(x: float, nd: int = 1) -> str:
    """A fraction as a percentage number (without the % sign)."""
    return fmt(100 * x, nd)


def count(n: int) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def money(x: float) -> str:
    return f"{x:,.2f}".replace(",", "{,}")


# ---- registry and lookup ----------------------------------------------------------------------

class Registry:
    """Macro name -> value. Names are letters only and unique."""

    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def add(self, name: str, value: str) -> None:
        if not re.fullmatch(r"[A-Za-z]+", name or ""):
            raise ValueError(f"macro name must be letters only: {name!r}")
        if name in self.values:
            raise ValueError(f"duplicate macro name: {name}")
        self.values[name] = str(value)

    def render(self) -> str:
        head = ["% Generated by make_numbers.py from the result JSON files. Do not edit by hand.",
                "% Regenerate: python3 paper/cace/make_numbers.py"]
        return "\n".join(head + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.values.items())]) + "\n"


def get(obj, path, source: str):
    """Look up a dotted path (or a sequence of keys, for keys that contain dots). Names the file and path on failure."""
    keys = path.split(".") if isinstance(path, str) else list(path)
    cur = obj
    for k in keys:
        try:
            cur = cur[k]
        except (KeyError, IndexError, TypeError):
            raise KeyError(f"{source}: missing key path {'.'.join(map(str, keys))!r} (at {k!r})") from None
    return cur


@lru_cache(maxsize=None)
def load(path: Path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


# ---- macro groups -----------------------------------------------------------------------------

def _dataset(r: Registry) -> None:
    eqs = load(ROOT / "unified_equations.json")
    eqs = eqs if isinstance(eqs, list) else eqs.get("equations", [])
    src = Counter((e.get("source_id") or "unknown").strip() for e in eqs)
    ref = {s: n for s, n in src.items() if s.startswith("handbook_")}
    r.add("NEq", count(len(eqs)))
    r.add("NSources", count(len(src)))
    r.add("NRefSets", count(len(ref)))
    r.add("NEqRef", count(sum(ref.values())))
    r.add("NPdf", count(len(src) - len(ref)))
    r.add("NEqPdf", count(len(eqs) - sum(ref.values())))

    name = "data_counts.json"
    d = get(load(KATO / name), "new", name)
    v = get(d, "by_variant", name)
    r.add("NCases", count(get(d, "n_cases", name)))
    r.add("NSingle", count(v["original"]))
    r.add("NCross", count(v["multisource_original"] + v["multisource_random_io"] + v["multisource_v3"]))
    r.add("NCrossPicked", count(v["multisource_original"]))
    r.add("NCrossReselected", count(v["multisource_random_io"]))
    r.add("NCrossProgram", count(v["multisource_v3"]))
    r.add("NSynth", count(v["dae"]))
    t2 = get(d, "table2", name)
    for jp, code in (("単一出典", "Single"), ("出典横断", "Cross"), ("合成", "Synth")):
        r.add(f"MeanK{code}", fmt(t2[jp]["mean_K"], 2))
        r.add(f"MaxK{code}", str(t2[jp]["max_K"]))
    r.add("MeanKAll", fmt(get(d, "setting_A_mean_K", name), 2))
    r.add("ShareKTwoPlus", pct(get(d, "setting_A_share_K_ge_2", name)))
    r.add("NExcluded", count(len(load(ROOT / get(d, "exclude", name))["excluded_case_ids"])))


def _overall(r: Registry) -> None:
    name = "main.json"
    m = load(KATO / name)
    for s in ("A", "B"):
        for method, mc in METHODS.items():
            for metric, code in METRICS.items():
                e = get(m, ("table", s, method, metric), name)
                r.add(f"{code}{s}{mc}", fmt(e["mean"]))
                r.add(f"{code}{s}{mc}SD", fmt(e["std"]))


def _llm(r: Registry) -> None:
    name = "id_summary.json"
    d = load(LLM / name)
    main = load(KATO / "main.json")
    for s in ("A", "B"):
        st = get(d, ("settings", s), name)
        # the retrieval methods of id_summary.json must be the values of kato1021/main.json
        for meth, mk in (("proposed", "proposed_static"), ("baseline", "baseline_tfidf")):
            for key, mkey in (("recall@20", "Recall@20"), ("AP@20", "MAP@20")):
                if abs(st["methods"][meth][key]["mean"] - main["table"][s][mk][mkey]["mean"]) > 1e-9:
                    raise ValueError(f"{name}: {meth} {key} of setting {s} differs from kato1021/main.json")
        for llm, lc in LLMS.items():
            for key, code in (("recall@20", "Rec"), ("AP@20", "MapTw")):
                e = get(st, ("methods", llm, key), name)
                r.add(f"{code}{s}{lc}", fmt(e["mean"]))
                r.add(f"{code}{s}{lc}SD", fmt(e["sd"]))
                for ref, rc in (("proposed", "Prop"), ("baseline", "Base")):
                    c = get(st, ("compare", f"{llm} vs {ref}", key), name)
                    r.add(f"Gap{code}{s}{lc}{rc}", fmt(abs(c["mean_diff"])))
                    r.add(f"Wins{code}{s}{lc}{rc}", str(c["wins"]))
    st = get(d, ("settings", "A"), name)
    for kind, kc in KINDS.items():
        n = get(st, ("n_test_by_kind", kind), name)
        r.add(f"NTest{kc}Min", count(min(n.values())))
        r.add(f"NTest{kc}Max", count(max(n.values())))
        for meth, mc in (("proposed", "Prop"), ("baseline", "Base"), ("Opus 5.5", "Opus"), ("Haiku 5.5", "Haiku")):
            for key, code in (("recall@20", "Rec"), ("AP@20", "MapTw")):
                e = get(st, ("methods", meth, "by_kind", kind, key), name)
                r.add(f"{code}{kc}{mc}", fmt(e["mean"]))
                r.add(f"{code}{kc}{mc}SD", fmt(e["sd"]))


def build() -> Registry:
    r = Registry()
    _dataset(r)
    _overall(r)
    _llm(r)
    return r


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true", help="exit 1 if the file differs from a fresh build")
    args = ap.parse_args(argv)
    text = build().render()
    out = Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{out} is stale: run python3 paper/cace/make_numbers.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}: {len(text.splitlines()) - 2} macros")
    return 0


if __name__ == "__main__":
    sys.exit(main())
