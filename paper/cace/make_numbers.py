"""Generate numbers.tex: every number of the paper as a TeX macro, read from the result JSON files.

The text and tables of the paper use only these macros, so they cannot drift from the data.
Run after any result JSON changes:
    python3 paper/cace/make_numbers.py            # writes paper/cace/numbers.tex
    python3 paper/cace/make_numbers.py --check    # exit 1 if numbers.tex differs from a fresh build

Conventions
  - Metrics print with three decimals; a value that rounds to zero prints without a minus sign.
  - A difference is rounded after subtracting the raw values (never the rounded ones).
  - Macro names are letters only (TeX reads \\Rec20A as \\Rec followed by "20A").
    Metric: Rec (Recall@20), Map (MAP), MapTw (MAP@20), RPrec (R-Precision).
    Setting: A (all 1,731 cases), B (the 1,000 synthesized cases).
    Method: Base (classical baseline), Bm (BM25 variant), EFive (E5 variant), Prop (static reranking),
            Infer (greedy at inference), Greedy (learned greedy), Opus, Haiku.  Suffix SD = standard deviation over 10 splits.
  - Signed differences (+0.075, -0.002) are meant for math mode: $\\DiffRecAPropBase$.
"""
