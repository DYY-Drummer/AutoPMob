# ---- formatting ------------------------------------------------------------------------------

def fmt(x: float, nd: int = 3) -> str:
    """Fixed decimals; a value that rounds to zero prints without a minus sign."""
    s = f"{x:.{nd}f}"
    return f"{0:.{nd}f}" if float(s) == 0 else s


def diff(a: float, b: float, nd: int = 3, signed: bool = True) -> str:
    """a - b from the raw values, rounded. signed adds + or -; a difference that rounds to zero has no sign."""
    d = a - b
    s = fmt(abs(d), nd)
    if float(s) == 0 or not signed:
        return s
    return ("+" if d > 0 else "-") + s


def pct(x: float, nd: int = 1) -> str:
    """A fraction as a percentage number (without the % sign)."""
    return fmt(100 * x, nd)


def count(n: int) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def money(x: float) -> str:
    return f"{x:,.2f}".replace(",", "{,}")


# ---- registry and lookup ----------------------------------------------------------------------

class Registry:
    """Macro name -> value. Names are letters only and unique."""

    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def add(self, name: str, value: str) -> None:
        if not re.fullmatch(r"[A-Za-z]+", name or ""):
            raise ValueError(f"macro name must be letters only: {name!r}")
        if name in self.values:
            raise ValueError(f"duplicate macro name: {name}")
        self.values[name] = str(value)

    def render(self) -> str:
        head = ["% Generated by make_numbers.py from the result JSON files. Do not edit by hand.",
                "% Regenerate: python3 paper/cace/make_numbers.py"]
        return "\n".join(head + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.values.items())]) + "\n"


def get(obj, path, source: str):
    """Look up a dotted path (or a sequence of keys, for keys that contain dots). Names the file and path on failure."""
    keys = path.split(".") if isinstance(path, str) else list(path)
    cur = obj
    for k in keys:
        try:
            cur = cur[k]
        except (KeyError, IndexError, TypeError):
            raise KeyError(f"{source}: missing key path {'.'.join(map(str, keys))!r} (at {k!r})") from None
    return cur


@lru_cache(maxsize=None)
def load(path: Path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


# ---- macro groups -----------------------------------------------------------------------------

def sdiff(delta: float, nd: int = 3) -> str:
    """A signed difference that is already a raw difference (for math mode)."""
    return diff(delta, 0.0, nd)


def require(cond: bool, claim: str) -> None:
    """Stop when the data no longer support a sentence that the text states without a number."""
    if not cond:
        raise ValueError(f"the text claims: {claim} -- the data no longer support it")


